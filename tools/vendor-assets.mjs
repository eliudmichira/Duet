rmSync(join(OUT, "avatars"), { recursive: true, force: true });
mkdirSync(join(OUT, "avatars"), { recursive: true });
AVATARS.forEach(([seed, bg], i) => {
  // Same options the old api.dicebear.com/9.x URLs used, so faces don't change.
  const svg = createAvatar(adventurer, {
    seed,
    backgroundColor: bg.split(","),
    backgroundType: ["gradientLinear"]
  }).toString();
  writeFileSync(join(OUT, "avatars", `av-${String(i).padStart(2, "0")}.svg`), svg);
});

// ── Twemoji ─────────────────────────────────────────────────
// Same matcher content.js uses to decide what to swap for an image.
const EMOJI_RE = /\p{Emoji_Presentation}|\p{Emoji}️/gu;

// Twemoji file naming: hex code points joined by "-", with U+FE0F dropped
// unless the sequence contains a ZWJ (mirrors twemoji's own lookup). Must
// match twemojiFile() in content.js.
function twemojiFile(emoji) {
  const text = emoji.includes("‍") ? emoji : emoji.replace(/️/g, "");
  return Array.from(text, ch => ch.codePointAt(0).toString(16)).join("-");
}

const sources = ["content.js", "popup.js"].map(f => readFileSync(join(EXT, f), "utf8"));
// Plus the status/system glyphs built at runtime from string pieces.
const extra = ["👋", "💬", "💞", "⏳", "⚠️", "🎬", "📺", "👤", "♥️"];
const found = new Set(extra);
for (const src of sources) {
  // Whole file, comments included: an extra file or two is cheaper than a
  // string-literal parser that trips over apostrophes.
  for (const [m] of src.matchAll(EMOJI_RE)) found.add(m);
}

const twemojiDir = dirname(require.resolve("@twemoji/svg/package.json"));
rmSync(join(OUT, "twemoji"), { recursive: true, force: true });
mkdirSync(join(OUT, "twemoji"), { recursive: true });
const bundled = [];
const missing = [];
for (const emoji of [...found].sort()) {
  const file = twemojiFile(emoji);
  const src = join(twemojiDir, `${file}.svg`);
  if (!existsSync(src)) { missing.push(`${emoji} (${file})`); continue; }
  copyFileSync(src, join(OUT, "twemoji", `${file}.svg`));
  bundled.push(file);
}
const uniq = [...new Set(bundled)].sort();

writeFileSync(join(OUT, "twemoji-set.js"),
`// Generated by tools/vendor-assets.mjs — do not edit by hand.
// Twemoji files bundled under vendor/twemoji/. Others render as system emoji.
globalThis.DUET_TWEMOJI = new Set(${JSON.stringify(uniq)});
`);

