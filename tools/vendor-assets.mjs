// ============================================================
//  Duet — vendor image assets into the extension
// ============================================================
// Regenerates, from npm packages (no network calls at runtime):
//   extension/vendor/avatars/av-NN.svg   — DiceBear "adventurer" portraits
//   extension/vendor/twemoji/<cp>.svg    — only the emoji Duet's UI uses
//   extension/vendor/twemoji-set.js      — which emoji are bundled
//   extension/vendor/CREDITS.txt         — attribution (CC BY 4.0 artwork)
//
// Usage:  cd tools && npm install && npm run vendor-assets
//
// Emoji are collected from string literals in content.js and popup.js, so
// adding an emoji to a picker and re-running this picks it up. Anything not
// bundled (e.g. an emoji typed into chat) renders as the system emoji.

import { readFileSync, writeFileSync, mkdirSync, rmSync, copyFileSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createAvatar } from "@dicebear/core";
import { adventurer } from "@dicebear/collection";

const require = createRequire(import.meta.url);
const HERE = dirname(fileURLToPath(import.meta.url));
const EXT = join(HERE, "..", "extension");
const OUT = join(EXT, "vendor");

// ── Avatars ─────────────────────────────────────────────────
